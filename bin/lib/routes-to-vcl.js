/*
 * Turn src/routes.js into a small set of Fastly VCL snippets.
 *
 * The previous approach created one Fastly condition + header (+ response
 * object for redirects) per route, accumulating hundreds of service objects and
 * needing a distinct synthetic status code per redirect. Instead the whole
 * route table is rendered into three snippets that are overwritten by name on
 * every deploy:
 *
 *   - init  "app-routes-tables": the redirect lookup table.
 *   - recv  "app-routes-recv":   redirect lookups (one reused status, keyed off
 *                                a slash-normalized path) and the app-route
 *                                rewrites to static html.
 *   - error "app-routes-error":  turn the reused status into a 301.
 *
 * A single reused internal status drives every redirect, so new redirects are
 * just new table rows -- no more running out of synthetic status codes.
 *
 * The S3-vs-dynamic backend split and the response TTL rules stay in the
 * recv-condition/fetch-condition custom VCL includes. Those run after the
 * #FASTLY recv/fetch macros; a snippet runs before the macro's default-backend
 * assignment, so it cannot set the backend reliably (the default would clobber
 * it). Snippets only do what survives that -- req.url rewrites and error-driven
 * redirects.
 *
 * Returns an array of snippet specs: {name, type, priority, content}.
 */

// Internal-only status used to signal "issue a redirect": caught in the error
// snippet and turned into a 301, never returned to a client. The value is
// arbitrary as long as it does not collide with a status another snippet in the
// service already uses (the feature snippets use 200/601/609/610/699).
const REDIRECT_STATUS = 700;

// Prepended to every generated snippet so it is obvious in the Fastly UI that
// the snippet is generated and where it comes from.
const GENERATED_HEADER = [
    '# Generated by bin/configure-fastly.js from src/routes.js.',
    '# Do not edit in Fastly; this snippet is overwritten on every deploy.'
].join('\n');

const withHeader = content => `${GENERATED_HEADER}\n\n${content}`;

// Escape a string for use inside a VCL double-quoted literal.
const vclString = value => `"${String(value).replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')}"`;

// Expand non-nested "(a|b)" and "(a|b)?" groups into every concrete alternative.
const expandGroups = body => {
    const match = body.match(/\(([^()]*)\)(\??)/);
    if (!match) return [body];
    const alternatives = match[1].split('|');
    if (match[2]) alternatives.push(''); // "(...)?" also matches nothing
    return alternatives.reduce((out, alt) => out.concat(
        expandGroups(body.slice(0, match.index) + alt + body.slice(match.index + match[0].length))
    ), []);
};

/*
 * Expand a redirect route's anchored pattern into the concrete literal paths it
 * matches, so each becomes a redirect-table key. Strips an optional trailing
 * "/?" and query group and handles simple "(a|b)" alternation, emitting one
 * slash-free key per alternative -- the recv snippet normalizes the request
 * path before the lookup, so the slashed form never needs its own key. Throws
 * if what remains is not a literal path, so a capturing/dynamic redirect can
 * never be silently dropped into an exact-match table -- it must be handled
 * explicitly instead.
 */
const redirectSourcePaths = route => {
    if (!route.pattern.startsWith('^')) {
        throw new Error(`Redirect pattern is not anchored at the start, cannot map to a table: ${route.pattern}`);
    }
    // Strip the leading "^" and an optional trailing "$"; a handful of patterns
    // omit the "$" but are still meant as exact paths (e.g. "^/info/donate/?").
    let body = route.pattern.replace(/^\^/, '').replace(/\$$/, '');
    body = body.replace(/\(\\\?\.\*\)\?$/, ''); // optional trailing "(\?.*)?" query group
    body = body.replace(/\/\?$/, ''); // optional trailing slash -- normalization covers the slashed form

    return expandGroups(body).reduce((paths, core) => {
        const literal = core.replace(/\\(.)/g, '$1');
        // A truly literal path re-escapes back to the pattern body it came from.
        const reEscaped = literal.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        if (reEscaped !== core) {
            throw new Error(`Redirect pattern is not a literal path, cannot map to a table: ${route.pattern}`);
        }
        paths.push(literal);
        return paths;
    }, []);
};

const renderTable = (name, entries) => {
    const rows = entries.map(([key, value]) => `    ${vclString(key)}: ${vclString(value)},`);
    return `table ${name} {\n${rows.join('\n')}\n}`;
};

// The clean-URL-to-static-html rewrite chain for the app (non-redirect) routes.
// Rendered as an if / else-if chain so the first matching route wins, matching
// the previous priority-ordered per-route rewrite headers. route.pattern is
// already a VCL regex (express params converted by the caller), so it is
// interpolated raw -- escaping its backslashes would change the regex.
const renderRewriteChain = appRoutes => {
    const branches = appRoutes.map((route, index) => {
        const keyword = index === 0 ? 'if' : '} else if';
        return `${keyword} (req.url.path ~ "${route.pattern}") {\n    set req.url = "/${route.name}.html";`;
    });
    return `${branches.join('\n')}\n}`;
};

/*
 * The recv body: run the redirect-table lookups first (so a redirect wins even
 * for a path the dynamic backend would otherwise serve), then the app-route
 * rewrites to their static html shells. The backend split (and the host /
 * language / XFF handling that goes with it) stays in the recv-condition custom
 * VCL include, which runs after the #FASTLY recv default-backend assignment -- a
 * snippet runs before it and cannot set req.backend reliably.
 *
 * The lookup is keyed off a slash-normalized copy of the path so a single
 * slash-free table key matches both "/foo" and "/foo/" -- but the request URL
 * itself is left untouched (no trailing-slash redirect). Adding a trailing slash
 * is left to the dynamic backend for the paths it owns; stripping one would
 * fight that and is unnecessary for the static routes, which serve either form.
 */
const renderRecv = appRoutes => {
    const lines = [
        '# Slash-normalized copy of the path, used only to look up the redirect',
        '# table so one slash-free key matches both "/foo" and "/foo/". The request',
        '# URL is not modified; this drives no redirect on its own.',
        'declare local var.path STRING;',
        'declare local var.redirect STRING;',
        'set var.path = regsub(req.url.path, "(.)/+$", "\\1");',
        '',
        '# Redirect exact/legacy paths to their destination (single reused status).',
        'set var.redirect = table.lookup(redirects, var.path, "");',
        'if (var.redirect != "") {',
        '    set req.http.X-Redirect-Location = var.redirect;',
        `    error ${REDIRECT_STATUS};`,
        '}',
        '',
        '# Legacy ?tip_bar= query redirects to the ?tutorial= equivalent.',
        'if (req.url ~ "\\?tip_bar=") {',
        '    set req.http.X-Redirect-Location = regsub(req.url, "tip_bar=", "tutorial=");',
        `    error ${REDIRECT_STATUS};`,
        '}',
        '',
        '# Legacy /projects/embed/<id> redirects to /projects/<id>/embed.',
        'if (req.url.path ~ "^/projects/embed/(\\d+)") {',
        '    set req.http.X-Redirect-Location = "/projects/" + re.group.1 + "/embed";',
        `    error ${REDIRECT_STATUS};`,
        '}'
    ];

    if (appRoutes.length) {
        lines.push('', '# Rewrite app routes to their static html shell (recv-condition routes these to S3).');
        lines.push(renderRewriteChain(appRoutes));
    }

    return lines.join('\n');
};

const renderError = () => [
    `if (obj.status == ${REDIRECT_STATUS}) {`,
    '    set obj.status = 301;',
    '    set obj.response = "Moved Permanently";',
    '    set obj.http.Location = req.http.X-Redirect-Location;',
    '    synthetic {""};',
    '    return(deliver);',
    '}'
].join('\n');

/*
 * Render the routes into the generated snippet specs: the redirect lookup table,
 * the recv body (redirect lookups + app-route rewrites), and the error handler
 * that turns the reused status into a 301. The backend split and response TTL
 * remain in the recv-condition/fetch-condition custom VCL includes.
 *
 * @param {Array} routes the resolved routes (from src/routes.js), with express
 *                        patterns already converted to VCL regexes (e.g. via
 *                        fastlyConfig.expressPatternToRegex)
 */
const routesToSnippets = routes => {
    const redirectEntries = [];
    const appRoutes = [];

    routes.forEach(route => {
        if (route.redirect) {
            redirectSourcePaths(route).forEach(source => redirectEntries.push([source, route.redirect]));
            return;
        }
        if (!route.name) {
            throw new Error(`App route has no name to rewrite to: ${route.pattern}`);
        }
        appRoutes.push(route);
    });

    return [
        {
            name: 'app-routes-tables',
            type: 'init',
            priority: '100',
            content: withHeader(renderTable('redirects', redirectEntries))
        },
        {
            name: 'app-routes-recv',
            type: 'recv',
            priority: '100',
            content: withHeader(renderRecv(appRoutes))
        },
        {
            name: 'app-routes-error',
            type: 'error',
            priority: '100',
            content: withHeader(renderError())
        }
    ];
};

module.exports = {routesToSnippets, redirectSourcePaths, REDIRECT_STATUS};
