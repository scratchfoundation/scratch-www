/*
 * Fastly snippets that assign homepage visitors to donate-banner group A or B.
 *
 * Flow:
 *   1. A request hits Fastly for the homepage (`/` is rewritten to
 *      `/splash.html` by app-routes-recv).
 *   2. If the visitor already has a donate_banner_ab cookie, keep that group
 *      so reloads and later visits stay in the same bucket.
 *   3. Otherwise roll randombool(percent_b, 100). True → B, false → A.
 *   4. vcl_deliver adds Set-Cookie. That runs per request, even when the HTML
 *      is cached, so the homepage cache is not split by group.
 *   5. The React banner reads the cookie and sends it with analytics events.
 *
 * Configure the groups with DONATE_BANNER_AB_FORCE, DONATE_BANNER_AB_ENABLED,
 * and DONATE_BANNER_AB_PERCENT_B, then redeploy Fastly. Do not edit these
 * snippets in the Fastly UI; configure-fastly.js overwrites them.
 *
 *   force=A or B  → overwrite every homepage cookie to that group
 *   enabled=0     → same as force=A (kill switch), unless force is set
 *   percent_b=0   → all *new* visitors get A
 *   percent_b=50  → 50/50
 *   percent_b=100 → all *new* visitors get B
 *
 * Changing percent_b does not re-roll existing cookies. Use force to move
 * everyone onto one variant. Logged-in visitors are assigned too: a
 * scratchsessionsid cookie does not reliably mean logged in, and the client
 * only shows the banner to logged-out visitors.
 */

const {DONATE_BANNER_AB_COOKIE} = require('../../src/lib/donate-banner-ab');

const DEFAULT_ENABLED = true;
const DEFAULT_FORCE = '';
const DEFAULT_PERCENT_B = 50;

const GENERATED_HEADER = [
    '# Generated by bin/configure-fastly.js for the homepage donate banner A/B test.',
    '# Do not edit in Fastly; this snippet is overwritten on every deploy.',
    '# Toggle groups with DONATE_BANNER_AB_FORCE, DONATE_BANNER_AB_ENABLED, and',
    '# DONATE_BANNER_AB_PERCENT_B.'
].join('\n');

const withHeader = content => `${GENERATED_HEADER}\n\n${content}`;

const HOMEPAGE = 'req.url.path == "/splash.html"';

const parseEnabled = (value = '') => {
    if (value === '') {
        return DEFAULT_ENABLED;
    }
    const normalized = String(value);
    if (normalized === '1' || normalized === 'true') {
        return true;
    }
    if (normalized === '0' || normalized === 'false') {
        return false;
    }
    throw new Error(`DONATE_BANNER_AB_ENABLED must be 0 or 1, got ${value}`);
};

const parsePercentB = (value = '') => {
    const raw = value === '' ? String(DEFAULT_PERCENT_B) : String(value);
    const percentB = Number.parseInt(raw, 10);
    if (!Number.isInteger(percentB) || percentB < 0 || percentB > 100 || String(percentB) !== raw) {
        throw new Error(`DONATE_BANNER_AB_PERCENT_B must be an integer 0-100, got ${value}`);
    }
    return percentB;
};

const parseForce = (value = '') => {
    if (value === '') {
        return DEFAULT_FORCE;
    }
    const normalized = String(value).toUpperCase();
    if (normalized === 'A' || normalized === 'B') {
        return normalized;
    }
    throw new Error(`DONATE_BANNER_AB_FORCE must be A, B, or empty, got ${value}`);
};

const renderForcedVariant = force => [
    `# Force ${force}: overwrite donate_banner_ab on the homepage.`,
    `if (${HOMEPAGE}) {`,
    `    set req.http.X-Donate-Banner-Variant = "${force}";`,
    '}'
].join('\n');

const renderRecv = ({enabled, force, percentB}) => {
    if (force === 'A' || force === 'B') {
        return renderForcedVariant(force);
    }
    if (!enabled) {
        return renderForcedVariant('A');
    }

    return [
        `# Experiment on: sticky cookie, otherwise ${percentB}% of new visitors get B.`,
        `if (${HOMEPAGE}) {`,
        `    if (req.http.Cookie:${DONATE_BANNER_AB_COOKIE} ~ "^[AB]$") {`,
        `        set req.http.X-Donate-Banner-Variant = req.http.Cookie:${DONATE_BANNER_AB_COOKIE};`,
        `    } else if (randombool(${percentB}, 100)) {`,
        '        set req.http.X-Donate-Banner-Variant = "B";',
        '    } else {',
        '        set req.http.X-Donate-Banner-Variant = "A";',
        '    }',
        '}'
    ].join('\n');
};

const renderDeliver = () => {
    const setCookieValue = [
        `"${DONATE_BANNER_AB_COOKIE}="`,
        'req.http.X-Donate-Banner-Variant',
        '"; Max-Age=31536000; Path=/; SameSite=Lax; Secure"'
    ].join(' + ');

    return [
        '# Stamp the group on the HTML response without Vary-ing the cached object.',
        `if (${HOMEPAGE} && req.http.X-Donate-Banner-Variant ~ "^[AB]$") {`,
        `    add resp.http.Set-Cookie = ${setCookieValue};`,
        '}'
    ].join('\n');
};

const donateBannerAbSnippets = ({
    enabled = DEFAULT_ENABLED,
    force = DEFAULT_FORCE,
    percentB = DEFAULT_PERCENT_B
} = {}) => [
    {
        name: 'donate-banner-ab-recv',
        type: 'recv',
        // After app-routes-recv (priority 100) rewrites `/` to `/splash.html`.
        priority: '110',
        content: withHeader(renderRecv({enabled, force, percentB}))
    },
    {
        name: 'donate-banner-ab-deliver',
        type: 'deliver',
        priority: '100',
        content: withHeader(renderDeliver())
    }
];

const donateBannerAbSnippetsFromEnv = (env = process.env) => donateBannerAbSnippets({
    enabled: parseEnabled(env.DONATE_BANNER_AB_ENABLED),
    force: parseForce(env.DONATE_BANNER_AB_FORCE),
    percentB: parsePercentB(env.DONATE_BANNER_AB_PERCENT_B)
});

module.exports = {
    DEFAULT_ENABLED,
    DEFAULT_FORCE,
    DEFAULT_PERCENT_B,
    donateBannerAbSnippets,
    donateBannerAbSnippetsFromEnv,
    parseEnabled,
    parseForce,
    parsePercentB
};
